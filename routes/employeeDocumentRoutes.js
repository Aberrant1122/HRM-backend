const router=require('express').Router(),m=require('../models'),c=require('../controllers/employeeDocumentController')(m),roles=require('../controllers/hrDocumentRoleController')(m,c);
router.use((req,res,next)=>{res.setHeader('Cache-Control','private, no-store');next();});
router.use('/deliveries',require('../controllers/documentDeliveryRoutes')(m,c));
router.use(c.authorize);
router.use('/signatures',require('../controllers/documentSignatureRoutes')(m,c));
const exchanges = require('../controllers/documentExchangeController')(m,c);
router.get('/exchanges',exchanges.list);
router.post('/exchanges/commands',exchanges.command);
const expiry=require('../controllers/documentExpiryController')(m,c);
router.get('/expiry',expiry.queue);
router.get('/expiry/:revisionId',expiry.details);
router.post('/expiry/commands',expiry.write);
router.get('/targets/:employeeId',c.target);
router.get('/options',c.options);
router.get('/roles/:userId',roles.read);
router.post('/roles/commands',roles.command);
router.get('/',c.list);
router.get('/employee/:employeeId',c.list);
router.get('/revisions/:revisionId/download',(req,res)=>c.download(req,res));
router.post('/uploads',require('../middleware/employeeDocumentUpload'),c.upload);
router.get('/:documentId/revisions',c.revisions);
router.get('/:documentId',c.read);
module.exports=router;
